const registered = new Set<string>();

/**
 * Registers a font set's faces the first time the reader shows it, so the
 * app never fetches a typeface the user does not pick. Latin subset only.
 */
export function registerFontSet(set: FontSet) {
  for (const family of families[set]) registerFamily(family);
}

/** The note editor's face (`font.writing`), registered when the editor first loads. */
export const registerWritingFont = () => registerFamily(sourceSerif4);

function registerFamily([family, faces]: Family) {
  for (const [url, weight, style = "normal"] of faces) {
    if (registered.has(url)) continue;
    registered.add(url);
    document.fonts.add(
      new FontFace(family, `url(${url}) format("woff2")`, { weight, style, display: "swap" }),
    );
  }
}
