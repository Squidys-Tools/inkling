import { randomUUID } from "node:crypto";
import { copyFile, link, mkdir, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import sharp from "sharp";
import { openDatabase } from "../../packages/library/src/storage/schema.ts";

/** Written into every generated library; the frame benchmark refuses a folder without it. */
export const benchMarker = ".inkling-bench";

// Share of each kind, out of 100. Kinds are the ones the library stores.
const kindMix = [
  ["image", 38],
  ["url", 22],
  ["note", 14],
  ["quote", 10],
  ["video", 5],
  ["pdf", 4],
  ["post", 4],
  ["file", 3],
] as const;
type Kind = (typeof kindMix)[number][0];

// Real photo sizes in both orientations, so the masonry grid gets mixed heights.
const photoSizes = [
  [3000, 2000],
  [2000, 3000],
  [3000, 3000],
  [4000, 2250],
  [2400, 3200],
] as const;
const thumbnailEdge = 512;

const words =
  "light harbor quiet winter field paper stone river morning studio letter garden glass orbit signal market copper meadow archive window ember coastline lantern pattern atlas thread velvet canyon ferry orchard pixel sketch".split(
    " ",
  );
const sites = ["example.com", "news.example.org", "blog.example.net", "docs.example.dev"];
const tags = ["design", "photography", "reading", "travel", "recipes", "work", "ideas", "music"];

/** A seeded generator, so the same arguments always write the same library. */
function random(seed: number) {
  let state = seed >>> 0;
  const next = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
  const int = (max: number) => Math.floor(next() * max);
  const pick = <T>(values: readonly T[]) => values[int(values.length)];
  const sentence = (count: number) => {
    const text = Array.from({ length: count }, () => pick(words)).join(" ");
    return text[0].toUpperCase() + text.slice(1);
  };
  return { next, int, pick, sentence };
}

// A smooth two-color gradient under per-pixel grain: JPEG sizes land near a real
// photo's (a few MB), where flat color or pure noise would be far off.
async function writePhoto(path: string, width: number, height: number, seed: number) {
  const rng = random(seed);
  const from = [rng.int(256), rng.int(256), rng.int(256)];
  const to = [rng.int(256), rng.int(256), rng.int(256)];
  const pixels = Buffer.alloc(width * height * 3);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const t = (x / width + y / height) / 2;
      const offset = (y * width + x) * 3;
      for (let channel = 0; channel < 3; channel++) {
        const grain = (rng.next() - 0.5) * 48;
        const value = from[channel] + (to[channel] - from[channel]) * t + grain;
        pixels[offset + channel] = value < 0 ? 0 : value > 255 ? 255 : value;
      }
    }
  }
  const image = sharp(pixels, { raw: { width, height, channels: 3 } });
  await image.clone().jpeg({ quality: 88 }).toFile(path);
  const thumbnail = await image
    .resize({ width: thumbnailEdge, height: thumbnailEdge, fit: "inside" })
    .webp({ quality: 78, effort: 2 })
    .toBuffer();
  const palette = [from, to, from.map((value, index) => (value + to[index]) >> 1)].map(
    (rgb) => `#${rgb.map((value) => value.toString(16).padStart(2, "0")).join("")}`,
  );
  return { thumbnail, palette: [...palette, palette[0], palette[1]] };
}

// A hard link costs no disk, so 10,000 items need only the pool of distinct photos;
// each item still has its own file and URL, so the renderer decodes each one.
async function place(source: string, target: string) {
  try {
    await link(source, target);
  } catch {
    await copyFile(source, target);
  }
}

/**
 * Writes a scratch library of `items` items through the library's own schema
 * code: photos at real camera sizes with their thumbnails, articles, notes,
 * quotes, videos, PDFs, posts and files, a few Spaces, and no pending jobs, so
 * nothing runs in the background while the benchmark measures.
 */
export async function generateLibrary({
  directory,
  items,
  photos = 40,
  seed = 1,
  assets = true,
}: {
  directory: string;
  items: number;
  photos?: number;
  seed?: number;
  /** Rows only, for measuring queries: thumbnails are referenced but not written. */
  assets?: boolean;
}) {
  await mkdir(directory, { recursive: true });
  if ((await readdir(directory)).length > 0)
    throw new Error(`${directory} is not empty; the generator writes only into a new folder.`);
  await writeFile(join(directory, benchMarker), "generated by tools/bench\n");
  const itemsDirectory = join(directory, "assets", "items");
  const poolDirectory = join(directory, "bench-pool");
  await mkdir(itemsDirectory, { recursive: true });

  const rng = random(seed);
  const pool: {
    file: string;
    thumbnail: string;
    width: number;
    height: number;
    palette: string[];
  }[] = [];
  if (assets) {
    await mkdir(poolDirectory, { recursive: true });
    for (let index = 0; index < photos; index++) {
      const [width, height] = photoSizes[index % photoSizes.length];
      const file = join(poolDirectory, `photo-${index}.jpg`);
      const { thumbnail, palette } = await writePhoto(file, width, height, seed * 1000 + index);
      const thumbnailFile = join(poolDirectory, `photo-${index}.webp`);
      await writeFile(thumbnailFile, thumbnail);
      pool.push({ file, thumbnail: thumbnailFile, width, height, palette });
    }
  } else {
    for (let index = 0; index < photos; index++) {
      const [width, height] = photoSizes[index % photoSizes.length];
      pool.push({ file: "", thumbnail: "", width, height, palette: [] });
    }
  }

  const { db } = openDatabase(join(directory, "library.sqlite3"));
  const insert = db.prepare(`INSERT INTO items (id, kind, title, description, body, body_format,
    source_url, source_label, local_asset_path, thumbnail_path, metadata, ocr_text, created_at,
    updated_at, archived) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, '', ?, ?, ?)`);
  const kinds = kindMix.flatMap(([kind, share]) => Array<Kind>(share).fill(kind));
  const now = Date.now();
  const ids: string[] = [];
  const fileWrites: (() => Promise<void>)[] = [];

  db.exec("BEGIN");
  try {
    for (let index = 0; index < items; index++) {
      const id = randomUUID();
      ids.push(id);
      const kind = rng.pick(kinds);
      // Newest first, about six minutes apart, so the order is the insert order.
      const createdAt = now - index * 6 * 60_000 - rng.int(60_000);
      const site = rng.pick(sites);
      const title = rng.sentence(3 + rng.int(6));
      const metadata: Record<string, unknown> = {
        tags: [rng.pick(tags), rng.pick(tags)].filter((tag, at, all) => all.indexOf(tag) === at),
      };
      let row = {
        title: title as string | null,
        description: null as string | null,
        body: "",
        bodyFormat: "md",
        sourceUrl: null as string | null,
        sourceLabel: null as string | null,
        asset: null as string | null,
        thumbnail: null as string | null,
      };
      const itemDirectory = join(itemsDirectory, id);
      const photoAssets = (fileName: string | null) => {
        const photo = pool[index % pool.length];
        metadata.mediaWidth = photo.width;
        metadata.mediaHeight = photo.height;
        if (photo.palette.length) metadata.palette = photo.palette;
        if (assets)
          fileWrites.push(async () => {
            await mkdir(itemDirectory, { recursive: true });
            await place(photo.thumbnail, join(itemDirectory, "thumbnail.webp"));
            if (fileName) await place(photo.file, join(itemDirectory, fileName));
          });
        return {
          asset: fileName ? `assets/items/${id}/${fileName}` : null,
          thumbnail: `assets/items/${id}/thumbnail.webp`,
        };
      };

      switch (kind) {
        case "image": {
          const fileName = `IMG_${String(1000 + index).padStart(5, "0")}.jpg`;
          Object.assign(metadata, { fileName, mimeType: "image/jpeg" });
          row = { ...row, title: fileName, sourceLabel: "image/jpeg", ...photoAssets(fileName) };
          break;
        }
        case "url": {
          const text = Array.from({ length: 6 }, () => rng.sentence(14)).join(". ");
          const sourceUrl = `https://${site}/${title.toLowerCase().replaceAll(" ", "-")}`;
          Object.assign(metadata, {
            sourceUrl,
            text,
            html: `<article><h1>${title}</h1><p>${text}</p></article>`,
            author: rng.sentence(2),
            readingMinutes: 2 + rng.int(12),
          });
          row = {
            ...row,
            description: text.slice(0, 180),
            sourceUrl,
            sourceLabel: site,
            ...(rng.next() < 0.5 ? photoAssets(null) : {}),
          };
          break;
        }
        case "note": {
          const body = `# ${title}\n\n${Array.from({ length: 1 + rng.int(4) }, () => rng.sentence(18)).join(".\n\n")}.`;
          row = {
            ...row,
            title: rng.next() < 0.7 ? title : null,
            body,
            description: body.slice(2, 182),
          };
          break;
        }
        case "quote": {
          const quote = `${rng.sentence(10 + rng.int(20))}.`;
          const attribution = rng.sentence(2);
          Object.assign(metadata, {
            quoteText: quote,
            attribution,
            text: `${quote}\n\n${attribution}`,
          });
          row = {
            ...row,
            title: quote,
            description: attribution,
            bodyFormat: "",
            sourceLabel: attribution,
          };
          break;
        }
        case "video": {
          const sourceUrl = `https://www.youtube.com/watch?v=bench${index}`;
          Object.assign(metadata, { sourceUrl, durationSeconds: 60 + rng.int(1800) });
          row = { ...row, sourceUrl, sourceLabel: "youtube.com", ...photoAssets(null) };
          break;
        }
        case "pdf": {
          const fileName = `${title.replaceAll(" ", "-")}.pdf`;
          Object.assign(metadata, {
            fileName,
            mimeType: "application/pdf",
            pdfPageCount: 1 + rng.int(40),
          });
          row = { ...row, title: fileName, sourceLabel: "application/pdf", ...photoAssets(null) };
          break;
        }
        case "post": {
          const postId = String(1_800_000_000_000_000_000n + BigInt(index));
          const postUrl = `https://x.com/example/status/${postId}`;
          Object.assign(metadata, {
            sourceUrl: postUrl,
            social: {
              provider: "x",
              postUrl,
              postId,
              text: rng.sentence(24),
              authorName: rng.sentence(2),
              authorHandle: "example",
            },
          });
          row = { ...row, sourceUrl: postUrl, sourceLabel: "x.com" };
          break;
        }
        case "file": {
          const fileName = `${title.replaceAll(" ", "-")}.zip`;
          Object.assign(metadata, {
            fileName,
            mimeType: "application/zip",
            fileSizeBytes: 1_000 + rng.int(9_000_000),
          });
          row = { ...row, title: fileName, sourceLabel: "application/zip" };
          break;
        }
      }
      insert.run(
        id,
        kind,
        row.title,
        row.description,
        row.body,
        row.bodyFormat,
        row.sourceUrl,
        row.sourceLabel,
        row.asset,
        row.thumbnail,
        JSON.stringify(metadata),
        createdAt,
        createdAt,
        index % 50 === 49 ? 1 : 0,
      );
    }

    const insertSpace = db.prepare(`INSERT INTO spaces (id, name, color, query, kind, position,
      created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)`);
    const insertMember = db.prepare(
      "INSERT INTO space_items (space_id, item_id, added_at) VALUES (?, ?, ?)",
    );
    const spaces = [
      ["Photos", "blue", { kind: "image" }, "smart"],
      ["Reading list", "orange", { kind: "article" }, "smart"],
      ["Design", "purple", { tag: "design" }, "smart"],
      ["Trip ideas", "green", {}, "regular"],
      ["Moodboard", "pink", {}, "regular"],
    ] as const;
    spaces.forEach(([name, color, query, spaceKind], position) => {
      const spaceId = randomUUID();
      insertSpace.run(spaceId, name, color, JSON.stringify(query), spaceKind, position, now, now);
      if (spaceKind === "regular")
        for (let member = position; member < ids.length; member += 7)
          insertMember.run(spaceId, ids[member], now);
    });
    db.prepare("INSERT OR REPLACE INTO app_settings (key, value) VALUES (?, ?)").run(
      "onboarding_completed",
      "1",
    );
    db.exec("COMMIT");
  } catch (error) {
    db.exec("ROLLBACK");
    throw error;
  } finally {
    db.close();
  }
  for (const write of fileWrites) await write();
  return { directory, items };
}
